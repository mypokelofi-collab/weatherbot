def test_force_if_due_takes_the_best_side_at_the_venue_minimum():
    cfg = PolymarketConfig(force_min_trades=True, min_edge=0.5,
                            force_trade_before_close_s=120, min_seconds_to_resolution=60)
    pipe = PolymarketPipeline(cfg, equity=10_000)
    m = market_fixture()

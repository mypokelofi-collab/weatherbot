def test_lot_minimum_shares_can_still_miss_the_venues_minimum_order_value():
    # Regression, found live against Polymarket: a market with a 0.12 ask and
    # a 5-share lot minimum sizes 5 shares = $0.60, which the lot-size check
    # alone waves through but the real venue rejects (min order value $1).
    m = market_fixture(min_order_size=5, min_notional=1.0)
    yes, no = books(yes_ask=0.12, no_ask=0.86, size=600)
    a = assess(m, yes, no, model_p=0.30, equity=10_000, now_ms=0, min_edge=0.01)
    assert a.side == "yes" and a.cost == pytest.approx(0.13)
    # Rounded up to the smallest lot multiple that clears $1, not left at 5.
    assert a.shares * a.cost >= 1.0
    assert a.shares % m.min_order_size == 0
    assert a.tradable



async def test_forced_trade_fires_end_to_end_and_stays_out_of_calibration(monkeypatch):
    from flowbot.polymarket import engine as engine_mod

    cfg = PolymarketConfig(
        force_min_trades=True, min_edge=0.5,               # organic edge unreachable
        force_trade_before_close_s=600, min_seconds_to_resolution=60,
    )
    pipe = PolymarketPipeline(cfg, equity=10_000)
    pipe.latency_ms = 1
    pipe.bind(lambda: (64_000.0, 0.55), lambda: 0.0)

    fixed_now = 0
    monkeypatch.setattr(engine_mod.time, "time", lambda: fixed_now / 1000.0)

    m = market_fixture(end_ts=300_000)                     # 5 minutes out - inside 600s
    yes, no = books(yes_ask=0.50, no_ask=0.50)

    async def fake_discover(now_ms):
        return [m]

    async def fake_book(token_id):
        return yes if token_id == "t1" else no

    async def no_market(_id):
        return None

    pipe._discover_windows = fake_discover
    pipe.client.get_book = fake_book
    pipe.client.get_market = no_market

    out = await pipe.poll()
    assert len(out) == 1 and out[0].blockers[0].startswith("forced:")
    assert len(pipe.positions) == 1
    pos = pipe.positions[0]
    assert pos.forced and pos.shares == m.min_order_size

    # Settle it and confirm it never reaches the calibration set.
    fixed_now = 300_001
    await pipe._settle_due(fixed_now)
    assert pos.settled
    assert pipe.forecasts == []
    state = pipe.state()
    assert state["forced_stats"]["settled"] == 1
    assert state["calibration"] is None



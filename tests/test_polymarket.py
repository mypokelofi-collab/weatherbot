async def test_discover_windows_computes_the_slug_instead_of_searching():
    # The epoch in btc-updown-15m-<epoch> is the window's own open time,
    # aligned to window_seconds. 1789938900 % 900 == 0 (a real example).
    pipe = PolymarketPipeline(PolymarketConfig(window_seconds=900), equity=10_000)
    requested = []

    async def fake(slug):
        requested.append(slug)
        return market_fixture(id=slug, slug=slug) if slug.endswith("900") else None

    pipe.client.get_market_by_slug = fake
    now_ms = 1789938900_000 + 37_000     # 37s into the window
    out = await pipe._discover_windows(now_ms)

    assert requested == ["btc-updown-15m-1789938900", "btc-updown-15m-1789939800"]
    assert len(out) == 1                 # only the current window resolved
    assert out[0].slug == "btc-updown-15m-1789938900"


